import { الملف_التنفيذي_للمبادرة } from './developmentDecisionEngine';

export interface درس_مستفاد {
  المشكلة: string;
  سببها: string;
  الإجراء_المتخذ: string;
  النتيجة: string;
  التوصية_المستقبلية: string;
}

export interface سجل_معرفة_المبادرة {
  معرف_المبادرة: string;
  رقم_المبادرة: string;
  اسم_المبادرة: string;
  المديرية: string;
  القطاع: string;
  الحالة_التشغيلية: string;
  نسبة_الإنجاز: number;
  هل_المبادرة_ناجحة: boolean;
  هل_المبادرة_متعثرة: boolean;
  أسباب_النجاح_أو_التعثر: string[];
  الدروس_المستفادة: درس_مستفاد[];
  الممارسات_الفضلى: string[];
  قابليتها_للنماذج_المكررة: boolean;
}

export interface تحليل_أسباب_التعثر_المتكررة {
  السبب: string;
  عدد_الحالات: number;
  نسبة_التكرار: number;
  المديريات_الأكثر_تأثراً: string[];
  التوصية_المؤسسية: string;
}

export interface عامل_نجاح_تنموي {
  العامل: string;
  عدد_المبادرات_المستفيدة: number;
  نسبة_الأثر: number;
  أمثلة_ميدانية: string[];
}

export interface ملخص_المعرفة_المؤسسية {
  إجمالي_المبادرات_المحللة: number;
  نسبة_المبادرات_الناجحة: number;
  نسبة_المبادرات_المتعثرة: number;
  أبرز_أسباب_التعثر: تحليل_أسباب_التعثر_المتكررة[];
  أبرز_عوامل_النجاح: عامل_نجاح_تنموي[];
  المبادرات_النموذجية_القابلة_للمحاكاة: سجل_معرفة_المبادرة[];
  توصيات_التخطيط_المستقبلي: string[];
}

/**
 * يستخرج بطاقة الدروس المستفادة لكل مبادرة بناءً على ملفها التنفيذي الموحد
 */
export function استخراج_الدروس_المستفادة(ملف: الملف_التنفيذي_للمبادرة): درس_مستفاد[] {
  const دروس: درس_مستفاد[] = [];
  const { التحليل, المواد, المجتمع, الهندسة, الوثائق, الإجراءات, التوصيات } = ملف;

  // 1. درس التعثر والتوقف الإداري أو المجتمعي
  if (التحليل.الحالة_التشغيلية.includes('متوقفة') || التحليل.الحالة_التشغيلية.includes('متعثرة')) {
    دروس.push({
      المشكلة: `تعثر المبادرة وتوقف الأعمال عند نسبة إنجاز ${التحليل.نسبة_الإنجاز}%`,
      سببها: `ضعف التنسيق الميداني أو نشوب نزاع مجتمعي في مسار الطريق/المشروع مع تأخر حشد المساهمة (المحشود ${المجتمع.نسبة_المساهمة}%)`,
      الإجراء_المتخذ: الإجراءات[0]?.العنوان || 'تشكيل لجنة تحكيم مجتمعي بقيادة السلطة المحلية وفارس التنمية',
      النتيجة: 'معالجة جزئية للنزاع وتثبيت مسار المشروع مع إعادة فتح المحضر',
      التوصية_المستقبلية: 'تشكيل لجنة تنازلات مجتمعية موثقة رسمياً قبل تسليم مواد الأسمنت والديزل لضمان عدم توقف المشروع'
    });
  }

  // 2. درس راكد ورعاية الأسمنت
  if (المواد.الإسمنت.المتبقي_لدى_المبادرة > 150) {
    دروس.push({
      المشكلة: `تراكم وتكدس أسمنت راكد بالموقع (${المواد.الإسمنت.المتبقي_لدى_المبادرة} كيس)`,
      سببها: 'صرف دفعة كبيرة من الأسمنت قبل اكتمال التجهيزات الترابية والمجاري السطحية للمبادرة',
      الإجراء_المتخذ: 'إلزام اللجنة بتسريع صبة المقاطع وتأمين المخزن بغطاء عازل للرطوبة',
      النتيجة: 'حماية الأسمنت من التصلب وتسريع وتيرة الرصف',
      التوصية_المستقبلية: 'اعتماد نظام الصرف المرحلي المرتبط بالإنجاز الفعلي (صب مقطع بـ 100 كيس يليه التوريد التالي)'
    });
  }

  // 3. درس الانحراف الهندسي والمواصفات
  if (الهندسة.هل_التنفيذ_مطابق_للدراسة !== 'مطابق' || التحليل.الحالة_الفنية.includes('انحراف')) {
    دروس.push({
      المشكلة: 'انحراف عن الجداول الهندسية أو معايير الرصف الجبلي',
      سببها: 'غياب الإشراف المباشر للمهندس أثناء تقطيع الأحجار وبناء الجدران الساندة',
      الإجراء_المتخذ: 'تعديل مسار الرصف وتأكيد التكحيل بالملاحط الإسمنتية الجافة وتصريف السيول',
      النتيجة: 'تصحيح معايير البناء وتثبيت الجدران الساندة قبل الموافقة على الدفعة التالية',
      التوصية_المستقبلية: 'اشتراط حضور المهندس المشرف في المحطات الرئيسية للرصف للتوقيع على المحضر الفني'
    });
  }

  // 4. درس المبادرات الناجحة والمكتملة
  if (التحليل.نسبة_الإنجاز >= 80) {
    دروس.push({
      المشكلة: 'لا يوجد تعثر - مبادرة عالية الأداء والإنجاز',
      سببها: 'التزام مجتمعي استثنائي بنسبة مساهمة high وتنسيق متناغم بين فارس التنمية ورئيس الجمعية',
      الإجراء_المتخذ: 'تسريع صرف الدفعات واستكمال توثيق صور الإنجاز محطة بمحطة',
      النتيجة: 'إنجاز المبادرة بجودة عالية وفي فترة قياسية',
      التوصية_المستقبلية: 'توثيق هذه المبادرة كموديل نموذجي وتكريم فرسان التنمية واللجنة الميدانية'
    });
  }

  // درس افتراضي عام إن لم تتطابق الشروط
  if (دروس.length === 0) {
    دروس.push({
      المشكلة: 'انضباط ميداني متوسط مع حاجة لاستكمال الأرشفة',
      سببها: 'تأخر بسيط في رفع كشوفات المساهمات وألبوم الصور عبر البوابة',
      الإجراء_المتخذ: 'توجيه فارس التنمية برفع كافة المستندات لتحديث الملف التنفيذي',
      النتيجة: 'تحديث بيانات المبادرة وانضباط شاشة المتابعة',
      التوصية_المستقبلية: 'استخدام تطبيق التقييم الميداني الذكي للرفع أولاً بأول'
    });
  }

  return دروس;
}

/**
 * يبني سجل المعرفة الكامل لمبادرة واحدة
 */
export function بناء_سجل_معرفة_المبادرة(ملف: الملف_التنفيذي_للمبادرة): سجل_معرفة_المبادرة {
  const { هوية_المبادرة, التحليل, المجتمع, المواد } = ملف;
  
  const هل_ناجحة = التحليل.نسبة_الإنجاز >= 75 && !التحليل.الحالة_التشغيلية.includes('متوقفة');
  const هل_متعثرة = التحليل.الحالة_التشغيلية.includes('متوقفة') || التحليل.الحالة_التشغيلية.includes('متعثرة');

  const أسباب: string[] = [];
  if (هل_ناجحة) {
    أسباب.push('تفاعل مجتمعي قوي بنسبة مساهمة عالية');
    أسباب.push('متابعة هندسية جيدة واستغلال ممتاز للأسمنت');
  }
  if (هل_متعثرة) {
    أسباب.push('نزاع مجتمعي أو توقف الصرف');
    أسباب.push('ضعف التنسيق الميداني وتأخر الإجراء الموصى به');
  }

  const ممارسات: string[] = [];
  if (المجتمع.نسبة_المساهمة >= 60) ممارسات.push('جمع المساهمات المجتمعية مقدماً قبل استلام الأسمنت');
  if (المواد.الإسمنت.المتبقي_لدى_المبادرة < 50 && التحليل.نسبة_الإنجاز > 50) ممارسات.push('السرعة الكبيرة في تفريغ الخرسانة وتجنب بقاء الأسمنت بالمستودع');
  if (ممارسات.length === 0) ممارسات.push('التنسيق المستمر مع قيادة السلطة المحلية والجمعية');

  return {
    معرف_المبادرة: هوية_المبادرة.معرف_المبادرة,
    رقم_المبادرة: هوية_المبادرة.رقم_المبادرة,
    اسم_المبادرة: هوية_المبادرة.اسم_المبادرة,
    المديرية: هوية_المبادرة.المديرية,
    القطاع: هوية_المبادرة.القطاع,
    الحالة_التشغيلية: التحليل.الحالة_التشغيلية,
    نسبة_الإنجاز: التحليل.نسبة_الإنجاز,
    هل_المبادرة_ناجحة: هل_ناجحة,
    هل_المبادرة_متعثرة: هل_متعثرة,
    أسباب_النجاح_أو_التعثر: أسباب,
    الدروس_المستفادة: استخراج_الدروس_المستفادة(ملف),
    الممارسات_الفضلى: ممارسات,
    قابليتها_للنماذج_المكررة: هل_ناجحة
  };
}

/**
 * يحلل قاعدة المعرفة التنموية الشاملة عبر جميع الملفات التنفيذية
 */
export function تحليل_قاعدة_المعرفة_التنموية(ملفات: الملف_التنفيذي_للمبادرة[]): ملخص_المعرفة_المؤسسية {
  const السجلات = ملفات.map(m => بناء_سجل_معرفة_المبادرة(m));
  const إجمالي = السجلات.length;

  const الناجحة = السجلات.filter(s => s.هل_المبادرة_ناجحة);
  const المتعثرة = السجلات.filter(s => s.هل_المبادرة_متعثرة);

  const نسبة_ناجحة = إجمالي > 0 ? Math.round((الناجحة.length / إجمالي) * 100) : 0;
  const نسبة_متعثرة = إجمالي > 0 ? Math.round((المتعثرة.length / إجمالي) * 100) : 0;

  // خريطة تجميع أسباب التعثر
  const mapReasons: Record<string, { count: number; districts: Set<string> }> = {
    'ضعف المساهمة المجتمعية ونشوب النزاعات': { count: 0, districts: new Set() },
    'تراكم الأسمنت والمواد دون تقدم بالرصف': { count: 0, districts: new Set() },
    'ملاحظات وانحرافات هندسية عن المواصفات': { count: 0, districts: new Set() },
    'نقص الوثائق الفنية وتأخر إجراءات المتابعة': { count: 0, districts: new Set() }
  };

  ملفات.forEach(m => {
    if (m.التحليل.الحالة_التشغيلية.includes('متوقفة') || m.المجتمع.نسبة_المساهمة < 40) {
      mapReasons['ضعف المساهمة المجتمعية ونشوب النزاعات'].count++;
      mapReasons['ضعف المساهمة المجتمعية ونشوب النزاعات'].districts.add(m.هوية_المبادرة.المديرية);
    }
    if (m.المواد.الإسمنت.المتبقي_لدى_المبادرة > 150) {
      mapReasons['تراكم الأسمنت والمواد دون تقدم بالرصف'].count++;
      mapReasons['تراكم الأسمنت والمواد دون تقدم بالرصف'].districts.add(m.هوية_المبادرة.المديرية);
    }
    if (m.الهندسة.هل_التنفيذ_مطابق_للدراسة !== 'مطابق' || m.التحليل.الحالة_الفنية.includes('انحراف')) {
      mapReasons['ملاحظات وانحرافات هندسية عن المواصفات'].count++;
      mapReasons['ملاحظات وانحرافات هندسية عن المواصفات'].districts.add(m.هوية_المبادرة.المديرية);
    }
    if (m.الوثائق.النواقص.length > 2) {
      mapReasons['نقص الوثائق الفنية وتأخر إجراءات المتابعة'].count++;
      mapReasons['نقص الوثائق الفنية وتأخر إجراءات المتابعة'].districts.add(m.هوية_المبادرة.المديرية);
    }
  });

  const أبرز_التعثر: تحليل_أسباب_التعثر_المتكررة[] = Object.entries(mapReasons).map(([reason, data]) => ({
    السبب: reason,
    عدد_الحالات: data.count,
    نسبة_التكرار: إجمالي > 0 ? Math.round((data.count / إجمالي) * 100) : 0,
    المديريات_الأكثر_تأثراً: Array.from(data.districts),
    التوصية_المؤسسية: reason.includes('مجتمعية') 
      ? 'اشتراط محضر تنازلات أرضية رسمية قبل الصرف' 
      : reason.includes('أسمنت') 
      ? 'اعتماد جدول الصرف المرحلي المرتبط بالاستهلاك' 
      : 'إلزام المهندس المشرف بالحضور الميداني يوماً بيوم'
  }));

  // عوامل النجاح
  const أبرز_النجاح: عامل_نجاح_تنموي[] = [
    {
      العامل: 'الحشد المجتمعي المبكر والالتزام بالمساهمة النقدية والعينية',
      عدد_المبادرات_المستفيدة: الناجحة.length,
      نسبة_الأثر: 92,
      أمثلة_ميدانية: الناجحة.slice(0, 3).map(n => n.اسم_المبادرة)
    },
    {
      العامل: 'التنسيق المتناغم بين فارس التنمية والجمعية والسلطة المحلية',
      عدد_المبادرات_المستفيدة: Math.max(1, الناجحة.length - 1),
      نسبة_الأثر: 88,
      أمثلة_ميدانية: الناجحة.slice(1, 4).map(n => n.اسم_المبادرة)
    },
    {
      العامل: 'السرعة القياسية في صب خرسانة الأسمنت فور استلام الدفعة',
      عدد_المبادرات_المستفيدة: الناجحة.filter(n => n.نسبة_الإنجاز >= 80).length,
      نسبة_الأثر: 85,
      أمثلة_ميدانية: الناجحة.filter(n => n.نسبة_الإنجاز >= 80).map(n => n.اسم_المبادرة)
    }
  ];

  const المبادرات_النموذجية = السجلات.filter(s => s.قابليتها_للنماذج_المكررة);

  const توصيات_مستقبلية = [
    'تطبيق آلية "التنازل المسبق" عن أراضي وحرم الطرق لتجنب التوقفات الناتجة عن النزاعات الأهليّة.',
    'اعتماد نظام الصرف المرحلي المقترن بنسبة إنجاز الرصف الحجري لمنع تراكم الأسمنت وتعرضه للرطوبة والتصلب.',
    'تفعيل دور فرسان التنمية كحلقة وصل دائمة لجمع كشوفات المساهمات وتوثيق التقدم المصور أولاً بأول.',
    'تعميم الممارسات الفضلى للمبادرات النموذجية على بقية المديريات المجاورة لرفع معدل الكفاءة.'
  ];

  return {
    إجمالي_المبادرات_المحللة: إجمالي,
    نسبة_المبادرات_الناجحة: نسبة_ناجحة,
    نسبة_المبادرات_المتعثرة: نسبة_متعثرة,
    أبرز_أسباب_التعثر: أبرز_التعثر,
    أبرز_عوامل_النجاح: أبرز_النجاح,
    المبادرات_النموذجية_القابلة_للمحاكاة: المبادرات_النموذجية,
    توصيات_التخطيط_المستقبلي: توصيات_مستقبلية
  };
}
