import { الملف_التنفيذي_للمبادرة } from './developmentDecisionEngine';

export type احتمالية_التعثر_نوع = 'منخفضة' | 'متوسطة' | 'مرتفع' | 'حرجة';
export type أولوية_التدخل_المبكر_نوع = 'لا يحتاج تدخل' | 'متابعة' | 'تدخل قريب' | 'تدخل عاجل';
export type تقييم_المسار_الزمني_نوع = 'منتظم حسب الخطة' | 'بطء متوسط' | 'تأخير ملحوظ' | 'تعثر وتوقف حاد';
export type كفاءة_توزيع_الموارد_نوع = 'استخدام كفء ومثالي' | 'أسمنت راكد بالموقع' | 'تحتاج صرف عاجل' | 'خطر هدر وتلف المواد';

export interface التحليل_التنبؤي_للمبادرة {
  احتمالية_التعثر: احتمالية_التعثر_نوع;
  أسباب_احتمالية_التعثر: string[];
  تقييم_المسار_الزمني: تقييم_المسار_الزمني_نوع;
  شرح_المسار_الزمني: string;
  كفاءة_توزيع_الموارد: كفاءة_توزيع_الموارد_نوع;
  تفاصيل_الموارد_التنبؤية: string;
  أولوية_التدخل_المبكر: أولوية_التدخل_المبكر_نوع;
  توصية_التدخل_الاستباقي: string;
  الجهة_المكلفة_بالتدخل: string;
  مؤشر_فرصة_الإغلاق_السريع: boolean;
  زمن_الإغلاق_المتوقع: string;
}

/**
 * محرك التحليل التنبؤي التنموي
 * يقرأ الملف التنفيذي الموحد للمبادرة ويستنتج التوقعات المستقبلية دون إجراء حسابات مستقلة
 */
export function تحليل_التنبؤ_التنموي(ملف: الملف_التنفيذي_للمبادرة): التحليل_التنبؤي_للمبادرة {
  const { التحليل, المواد, المجتمع, الوثائق, المؤشرات, التوصيات, الإجراءات } = ملف;

  const أسباب_التعثر: string[] = [];

  // 1. حساب احتمالية التعثر المستقبلية
  let احتمالية: احتمالية_التعثر_نوع = 'منخفضة';

  if (المؤشرات.درجة_الخطورة === 'حرج' || التحليل.الحالة_التشغيلية.includes('متوقفة') || التحليل.الحالة_التشغيلية.includes('متعثرة')) {
    احتمالية = 'حرجة';
    أسباب_التعثر.push(`توقف الأعمال الميدانية ونسبة الإنجاز عند ${التحليل.نسبة_الإنجاز}%`);
  } else if (المؤشرات.درجة_الخطورة === 'مرتفع' || التحليل.الحالة_التشغيلية.includes('بطيئة')) {
    احتمالية = 'مرتفع';
    أسباب_التعثر.push(`تباطؤ في الإنجاز الميداني مقارنة بجدول التوريد`);
  } else if (المؤشرات.درجة_الخطورة === 'متوسط') {
    احتمالية = 'متوسطة';
  }

  // إضافة أسباب من المواد والوثائق
  if (المواد.الإسمنت.المتبقي_لدى_المبادرة > 150 && التحليل.نسبة_الإنجاز < 40) {
    أسباب_التعثر.push(`وجود كمية أسمنت راكدة بالموقع (${المواد.الإسمنت.المتبقي_لدى_المبادرة} كيس) دون تقدم في الرصف الحجري`);
    if (احتمالية === 'متوسطة') احتمالية = 'مرتفع';
  }

  if (المجتمع.نسبة_المساهمة < 40) {
    أسباب_التعثر.push(`تأخر حشد المساهمة المجتمعية (المحشود ${المجتمع.نسبة_المساهمة}%)`);
  }

  if (الوثائق.النواقص.length > 2) {
    أسباب_التعثر.push(`نقص في الوثائق الفنية ورخص المحجر`);
  }

  if (أسباب_التعثر.length === 0) {
    أسباب_التعثر.push('التنفيذ يسير بشكل خالي من العوائق المباشرة');
  }

  // 2. تحليل المسار الزمني
  let مسار_زمني: تقييم_المسار_الزمني_نوع = 'منتظم حسب الخطة';
  let شرح_مسار = 'الأعمال الميدانية تتقدم بتناغم مع التوريد والصرف.';

  if (التحليل.نسبة_الإنجاز < 25 && المواد.الإسمنت.المنصرف > 100) {
    مسار_زمني = 'تأخير ملحوظ';
    شرح_مسار = 'معدل الإنجاز متأخر جداً مقارنة بحجم الأسمنت المنصرف للموقع.';
  } else if (التحليل.الحالة_التشغيلية.includes('بطيئة') || التحليل.نسبة_الإنجاز < 50) {
    مسار_زمني = 'بطء متوسط';
    شرح_مسار = 'يوجد تباطؤ في وتيرة الرصف يتطلب تنشيط المجتمع واللجنة الفنية.';
  } else if (التحليل.الحالة_التشغيلية.includes('متوقفة')) {
    مسار_زمني = 'تعثر وتوقف حاد';
    شرح_مسار = 'الأعمال متوقفة تماماً وتتطلب نزولاً ميدانياً عاجلاً لحل النزاع.';
  }

  // 3. كفاءة توزيع الموارد
  let كفاءة_موارد: كفاءة_توزيع_الموارد_نوع = 'استخدام كفء ومثالي';
  let تفاصيل_موارد = 'المواد المصروفة مستغلة بالكامل في الصبة حسب المواصفات الهندسية.';

  if (المواد.الإسمنت.المتبقي_لدى_المبادرة > 200 && التحليل.نسبة_الإنجاز < 30) {
    كفاءة_موارد = 'خطر هدر وتلف المواد';
    تفاصيل_موارد = `تراكم ${المواد.الإسمنت.المتبقي_لدى_المبادرة} كيس أسمنت بمخزن المبادرة معرضة للتصلب بالرطوبة.`;
  } else if (المواد.الإسمنت.المتبقي_لدى_المبادرة > 100) {
    كفاءة_موارد = 'أسمنت راكد بالموقع';
    تفاصيل_موارد = `يوجد أسمنت راكد بالموقع (${المواد.الإسمنت.المتبقي_لدى_المبادرة} كيس) يحتاج تسريع صب.`;
  } else if (التحليل.نسبة_الإنجاز > 60 && المواد.الإسمنت.المتبقي_لدى_المبادرة < 30 && المواد.الإسمنت.المتبقي_لدى_الوحدة > 0) {
    كفاءة_موارد = 'تحتاج صرف عاجل';
    تفاصيل_موارد = 'المبادرة متقدمة بالإنجاز والمستودع شبه فارغ، يوصى بصرف الدفعة التالية فوراً.';
  }

  // 4. مؤشر أولوية التدخل المبكر
  let تدخل_مبكر: أولوية_التدخل_المبكر_نوع = 'لا يحتاج تدخل';
  let توصية_تدخل = 'متابعة اعتيادية عبر التقارير الدورية المصورة.';
  let جهة_مكلفة = الإجراءات[0]?.الجهة_المسؤولة || 'المهندس الميداني';

  if (احتمالية === 'حرجة' || المؤشرات.درجة_الخطورة === 'حرج') {
    تدخل_مبكر = 'تدخل عاجل';
    توصية_تدخل = التوصيات[0] || 'نزول قيادي طارئ لحل العوائق وإحالة المخالفين.';
    جهة_مكلفة = 'مدير المديرية ورئيس الجمعية';
  } else if (احتمالية === 'مرتفع' || كفاءة_موارد === 'خطر هدر وتلف المواد') {
    تدخل_مبكر = 'تدخل قريب';
    توصية_تدخل = 'توجيه المهندس الميداني وفارس التنمية بإلزام اللجنة بتفريع الأسمنت.';
    جهة_مكلفة = 'فارس التنمية والمهندس المشرف';
  } else if (احتمالية === 'متوسطة') {
    تدخل_مبكر = 'متابعة';
    توصية_تدخل = 'تنشيط الحشد المجتمعي ومتابعة استكمال النواقص الوثائقية.';
    جهة_مكلفة = 'الجمعية التعاونية بالمديرية';
  }

  // 5. فرصة الإغلاق السريع
  const فرصة_إغلاق = التحليل.نسبة_الإنجاز >= 80 && الوثائق.النواقص.length <= 1;
  const زمن_إغلاق = فرصة_إغلاق 
    ? 'خلال 7 إلى 14 يوماً فور رفع ألبوم الصور ومحضر الاستلام'
    : 'يتطلب استكمال الأعمال الميدانية والنواقص أولاً';

  return {
    احتمالية_التعثر: احتمالية,
    أسباب_احتمالية_التعثر: أسباب_التعثر,
    تقييم_المسار_الزمني: مسار_زمني,
    شرح_المسار_الزمني: شرح_مسار,
    كفاءة_توزيع_الموارد: كفاءة_موارد,
    تفاصيل_الموارد_التنبؤية: تفاصيل_موارد,
    أولوية_التدخل_المبكر: تدخل_مبكر,
    توصية_التدخل_الاستباقي: توصية_تدخل,
    الجهة_المكلفة_بالتدخل: جهة_مكلفة,
    مؤشر_فرصة_الإغلاق_السريع: فرصة_إغلاق,
    زمن_الإغلاق_المتوقع: زمن_إغلاق
  };
}
